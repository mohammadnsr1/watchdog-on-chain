#!/usr/bin/env python3
"""Generate fixtures/merkle_fixture.json: a small Merkle tree built by wdchain.

The Foundry test `contracts/test/EvidenceRegistry.t.sol` reads this file, anchors the root and
checks every chunk's proof inside the contract. If Python and Solidity ever disagree about the
hashing scheme, that test fails.

Run before `forge test`:

    python3 scripts/make_merkle_fixture.py

The content is synthetic and deterministic: the same command always writes the same bytes, so
the fixture can be regenerated without churn. No session data is used.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from wdchain.evidence.canonical import canonical_bytes  # noqa: E402
from wdchain.evidence.merkle import (  # noqa: E402
    HASH_SCHEME,
    chunk_digest,
    leaf_from_digest,
    merkle_proof,
    merkle_root,
    to_hex,
)

DEFAULT_OUT = REPO_ROOT / "fixtures" / "merkle_fixture.json"
DEFAULT_N = 7  # odd count on purpose: exercises the carried-up odd node


def build_fixture(n_chunks: int = DEFAULT_N) -> dict:
    """Build `n_chunks` synthetic records and return the fixture document."""
    if n_chunks < 1:
        raise ValueError("n_chunks must be >= 1")

    # Records shaped like real WatchDog evidence, with fixed values so the output is stable.
    chunks = [
        canonical_bytes(
            {
                "wall_time_iso": f"2026-10-07T20:5{i // 10}:{i % 10:02d}.000000+00:00",
                "event_type": "monitor_fire" if i % 3 == 0 else "look",
                "seq": i + 1,
                "payload": {"monitor_id": f"mon_{i:04d}", "step_id": "pick_u_orange"},
            }
        )
        for i in range(n_chunks)
    ]

    digests = [chunk_digest(c) for c in chunks]
    leaves = [leaf_from_digest(d) for d in digests]
    root = merkle_root(leaves)

    return {
        "_comment": "Generated by scripts/make_merkle_fixture.py. Read by EvidenceRegistry.t.sol.",
        "hash_scheme": HASH_SCHEME,
        "n_chunks": n_chunks,
        "root": to_hex(root),
        "chunks": [
            {
                "index": i,
                "digest": to_hex(digests[i]),
                "leaf": to_hex(leaves[i]),
                "proof": [to_hex(h) for h in merkle_proof(leaves, i)],
            }
            for i in range(n_chunks)
        ],
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--n-chunks", type=int, default=DEFAULT_N)
    args = ap.parse_args(argv)

    fixture = build_fixture(args.n_chunks)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(fixture, indent=2) + "\n", encoding="utf-8")

    print(f"wrote {args.out}")
    print(f"  hash_scheme : {fixture['hash_scheme']}")
    print(f"  n_chunks    : {fixture['n_chunks']}")
    print(f"  root        : {fixture['root']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
